/**
 * 사용자 제공 문자열이 태그를 닫고 새 지시를 삽입하지 못하도록 이스케이프한 뒤
 * 명시적인 비신뢰 데이터 블록으로 감싼다.
 */
export const wrapUntrustedPromptData = (
  tag: UntrustedPromptDataTag,
  content: string,
): string => {
  const escapedContent = content
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');

  return `<${tag}>\n${escapedContent}\n</${tag}>`;
};

